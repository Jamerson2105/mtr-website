#!/usr/bin/env python3
"""Turn the photos in images/ into the website's scrolling gallery.

For every photo in images/ (except files with "logo" in the name):
- Resizes anything wider than 1600px down to 1600px (keeps aspect ratio, never upscales)
- Applies EXIF rotation so phone photos aren't sideways, then strips metadata (GPS etc.)
- Saves it as WebP (quality 80) in assets/img/gallery/: images/hackathon.jpg -> hackathon.webp

Then it rewrites js/gallery-data.js, the list of photos the gallery shows.
Captions/alt text come from the file name ("robot-demo_day.jpg" -> "Robot demo day"),
so name your files descriptively. Photos removed from images/ are removed from the gallery.
Photos appear in alphabetical order; prefix names with 01-, 02-, ... to control the order.

Usage (from the repo root):   python3 scripts/optimize_images.py
Requires Pillow:              pip install Pillow
"""
import json
import re
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "images"
DEST = ROOT / "assets" / "img" / "gallery"
DATA = ROOT / "js" / "gallery-data.js"
MAX_WIDTH = 1600
QUALITY = 80
EXTS = {".jpg", ".jpeg", ".png", ".webp", ".tif", ".tiff", ".bmp"}


def caption(stem: str) -> str:
    text = re.sub(r"^\d+[-_ ]*", "", stem)          # drop "01-" ordering prefix
    text = re.sub(r"[-_]+", " ", text).strip()
    return text[:1].upper() + text[1:] if text else "UW MedTechRobotics team activity"


def main() -> None:
    DEST.mkdir(parents=True, exist_ok=True)
    # The logo is handled separately (kept lossless at its original size)
    files = sorted(p for p in SRC.iterdir()
                   if p.suffix.lower() in EXTS and "logo" not in p.stem.lower())

    entries = []
    for src in files:
        out = DEST / f"{src.stem}.webp"
        with Image.open(src) as im:
            im = ImageOps.exif_transpose(im)
            if im.width > MAX_WIDTH:
                im = im.resize((MAX_WIDTH, round(im.height * MAX_WIDTH / im.width)), Image.LANCZOS)
            if im.mode not in ("RGB", "RGBA"):
                im = im.convert("RGBA" if "A" in im.getbands() else "RGB")
            im.save(out, "WEBP", quality=QUALITY, method=6)
            w, h = im.size
        entries.append({"src": f"assets/img/gallery/{out.name}", "alt": caption(src.stem),
                        "width": w, "height": h})
        print(f"{src.name:30} -> {out.relative_to(ROOT)}  {w}x{h}  "
              f"{src.stat().st_size // 1024} KB -> {out.stat().st_size // 1024} KB")

    # Remove gallery images whose originals were deleted from images/
    keep = {Path(e["src"]).name for e in entries}
    for old in DEST.glob("*.webp"):
        if old.name not in keep:
            old.unlink()
            print(f"removed {old.relative_to(ROOT)} (no longer in images/)")

    DATA.write_text(
        "// AUTO-GENERATED by scripts/optimize_images.py. You can edit captions here,\n"
        "// but re-running the script will overwrite this file.\n"
        f"window.GALLERY = {json.dumps(entries, indent=2)};\n"
    )
    print(f"\n{len(entries)} photo(s) in the gallery. Wrote {DATA.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
